"""Writes SYNTHETIC test signals (harmonic bursts, NOT speech) to data/synthetic_demo/ and registers them in
data/manifest.jsonl with ground-truth labels (annotation_method = injected_synthetic). They exist only to
smoke-test the pipeline/dashboard; they are not dataset evidence. Existing non-synthetic manifest entries are kept."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "tests"))
import soundfile as sf
from synth import SR, baseline, synth_speech

out = ROOT / "data" / "synthetic_demo"; out.mkdir(parents=True, exist_ok=True)
LIC = "generated by scripts/make_synthetic_demo.py (no third-party material)"
ref, _ = baseline(seed=1)
sf.write(out / "reference.wav", ref, SR)
cases = []

y, t = synth_speech([(18, 4.5), (36, 7.2), (36, 7.2), (18, 4.5)], [0.5] * 3, seed=3)
cases.append(("participant_rushed_middle", y, "Middle two phrases injected at 7.2 syl/s (reference 4.5).",
              [{"category": "rushed_pacing", "start_s": round(t["phrases"][1][0], 2), "end_s": round(t["phrases"][2][1], 2), "severity": 2}]))
y, t = baseline(seed=6, pitch_st=0.3)
cases.append(("participant_flat_pitch", y, "Whole signal with pitch variation reduced to 0.3 semitones.",
              [{"category": "monotone_delivery", "start_s": 0.6, "end_s": round(t["phrases"][-1][1], 2), "severity": 4}]))
y, t = synth_speech([(6, 4.5)] * 8, [1.4, 0.9, 0.9, 0.9, 0.9, 0.9, 0.9], seed=5)
cases.append(("participant_long_pauses", y, "Pauses of 0.9-1.4 s inserted between short phrases.",
              [{"category": "excessive_pauses", "start_s": round(a, 2), "end_s": round(b, 2), "severity": 2} for a, b in t["pauses"]]))
y, _ = baseline(seed=2, base_f0=210.0, gain_db=-32.0, noise_db=-60.0)
cases.append(("participant_clean_other_voice", y, "Same delivery, different voice/loudness/noise. Expected: no flags.", []))

recs = [{"id": "syn_ref", "passage_id": "syn", "speaker_id": "synthetic_a", "role": "reference",
         "audio_path": "synthetic_demo/reference.wav", "transcript": "", "flaw_labels": [], "synthetic": True,
         "license": LIC, "provenance": "synthetic test signal", "split": "demo"}]
for name, y, desc, labels in cases:
    sf.write(out / f"{name}.wav", y, SR)
    for l in labels:
        l["annotation_method"] = "injected_synthetic"
    recs.append({"id": f"syn_{name.replace('participant_', '')}", "passage_id": "syn", "speaker_id": "synthetic_b",
                 "role": "participant", "reference_id": "syn_ref", "audio_path": f"synthetic_demo/{name}.wav",
                 "transcript": "", "flaw_labels": labels, "synthetic": True, "description": desc,
                 "license": LIC, "provenance": "synthetic test signal", "split": "demo"})

mf = ROOT / "data" / "manifest.jsonl"
keep = []
if mf.exists():
    for line in mf.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            if not r.get("synthetic"):
                keep.append(r)
mf.write_text("\n".join(json.dumps(r) for r in keep + recs) + "\n", encoding="utf-8")
print(f"wrote {len(recs)} synthetic records ({len(keep)} existing real records kept) -> {mf}")
